"""Turns Course_List.xlsx into data.js (one record per course, groups listed once).
Run:  python3 tools/make_data.py ../Course_List.xlsx data.js
"""
import sys, os, csv, json, openpyxl

src, out = sys.argv[1], sys.argv[2]
wb = openpyxl.load_workbook(src, data_only=True)
ws = wb['Courses']

courses, groups = {}, {}
def gid(kind, name):
    return kind.lower() + ':' + name.lower().replace(' ', '-')

for r in range(5, ws.max_row + 1):
    sgs, hn, name, credits, cat, mm, rule = (ws.cell(r, c).value for c in (2, 3, 4, 5, 6, 7, 8))
    if cat not in ('Core', 'STEM Future Tech', 'Capstone', 'Major', 'Minor'):
        continue                       # skips blank rows, the example row, the note block
    if name in (None, 'Example Minor Course Name'):
        continue
    if cat in ('Major', 'Minor'):
        g = gid(cat, mm)
        groups.setdefault(g, {'id': g, 'type': cat, 'name': mm, 'rule': rule, 'members': [], 'mandatory': []})
        if not sgs:                    # placeholder row (e.g. Digital Economy: no published list)
            groups[g]['listMissing'] = True
            continue
    if not sgs:
        continue
    mandatory = name.endswith('— mandatory')
    name = name.replace(' — mandatory', '')
    c = courses.setdefault(sgs, {'id': sgs, 'hn': hn or None, 'name': name, 'credits': credits or 12,
                                 'required': cat in ('Core', 'STEM Future Tech', 'Capstone'),
                                 'category': cat if cat not in ('Major', 'Minor') else None,
                                 'groups': []})
    if cat in ('Major', 'Minor'):
        c['groups'].append(g)
        groups[g]['members'].append(sgs)
        if mandatory:
            groups[g]['mandatory'].append(sgs)

# how many courses each group needs: majors 8, minors 4 (never more than are listed)
for g in groups.values():
    full = 8 if g['type'] == 'Major' else 4
    g['need'] = min(full, len(g['members'])) if g['members'] else full

# offerings (SGS campus) from the Offering Schedule sheet: code -> {term: "Yes"/"Cancelled"/...}
wo = wb['Offering Schedule 2026']
terms = [wo.cell(5, c).value.replace('SGS ', '') for c in (5, 6, 7)]          # 2026-1, 2026-2, 2026-3
offerings = {}
for r in range(6, wo.max_row + 1):
    code = wo.cell(r, 2).value
    if not code:
        continue
    offerings[code] = {t: (wo.cell(r, 5 + i).value or '') for i, t in enumerate(terms)}

# Recommended order from the Program Plan Guide in ProgramStructure-BP162VI23.pdf:
# per semester, the required courses and how many open "Combination Course" slots there are.
SEQUENCE = [
    (1, ['COSC3104', 'COSC2174', 'INTE2633'], 0),
    (2, ['COSC3089', 'COSC3107'], 0),
    (3, ['COSC3110', 'COSC3060'], 0),
    (4, ['ISYS3416'], 2),
    (5, ['COSC2766'], 2),
    (6, ['COSC2767', 'COSC2968'], 1),
    (7, ['ISYS2101'], 2),
    (8, ['COSC2502', 'COSC2503'], 1),
]
seq_ids = [i for _, ids, _ in SEQUENCE for i in ids]
req_ids = [c['id'] for c in courses.values() if c['required']]
assert sorted(seq_ids) == sorted(req_ids), 'sequence must list every required course once'
assert sum(n for _, _, n in SEQUENCE) == 8, 'expected 8 open elective slots'
sequence = [{'sem': s, 'year': 1 if s <= 3 else 2 if s <= 6 else 3, 'courses': ids, 'open': n} for s, ids, n in SEQUENCE]

# Prerequisites: tools/prerequisites.csv (code, requisites, source, note). One row per course we know about.
# requisites = the handbook's "Enforced Course Requisites" text (SGS codes); an empty cell means none listed.
# A course with no row gets prereq = None, which the course list shows as "not recorded yet".
prereq_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'prerequisites.csv')
prereqs = {}
if os.path.exists(prereq_path):
    with open(prereq_path, newline='', encoding='utf-8') as f:
        for row in csv.DictReader(f):
            code = row['code'].strip()
            assert code in courses, 'prerequisites.csv: unknown course ' + code
            prereqs[code] = {'text': row['requisites'].strip(), 'source': row['source'].strip(), 'note': row['note'].strip()}
for cid, c in courses.items():
    c['prereq'] = prereqs.get(cid)

data = {'program': 'BP162VI23 (Saigon South)', 'terms': terms,
        'courses': list(courses.values()), 'groups': list(groups.values()), 'offerings': offerings, 'sequence': sequence}
open(out, 'w').write('// generated by tools/make_data.py - do not edit by hand\nwindow.DATA = ' +
                     json.dumps(data, indent=1) + ';\n')
print(len(courses), 'courses,', len(groups), 'groups,', len(offerings), 'offering rows')
