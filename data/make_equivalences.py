"""Turns data/equivalences.csv into programs/equivalences.js. Run from the project folder:
  python3 -I data/make_equivalences.py programs/equivalences.js
Each row says: a course the student completed in from_program (from_code) counts as to_code in to_program.
 - from_program different from to_program: used when a student copies progress to another program or edition
   (courses with the SAME code are matched automatically, so only list codes that changed).
 - from_program equal to to_program: the courses are interchangeable inside that program (completing from_code counts for to_code).
   For two-way equivalence add the row twice, once each way.
Lines starting with # are ignored. note = free text, e.g. why the course was replaced.
"""
import csv, sys, json
rows = []
with open('data/equivalences.csv', newline='', encoding='utf-8') as f:
    lines = [l for l in f if not l.lstrip().startswith('#')]
for r in csv.DictReader(lines):
    r = {k: (v or '').strip() for k, v in r.items()}
    if not r['from_code']: continue
    assert r['from_program'] and r['to_program'] and r['to_code'], 'incomplete row: %s' % r
    rows.append(r)
open(sys.argv[1], 'w').write('// generated by data/make_equivalences.py - do not edit by hand\nwindow.EQUIVALENCES = ' + json.dumps(rows, indent=1) + ';\n')
print(len(rows), 'equivalence rows')
